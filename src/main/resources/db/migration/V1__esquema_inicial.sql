-- Raízes do Nordeste - esquema inicial (PostgreSQL; compatível com H2 em modo PostgreSQL para testes)

CREATE TABLE unidade (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome    VARCHAR(120) NOT NULL,
    cidade  VARCHAR(80)  NOT NULL,
    uf      VARCHAR(2)   NOT NULL,
    ativa   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE produto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120)   NOT NULL,
    descricao   VARCHAR(500),
    categoria   VARCHAR(60)    NOT NULL,
    preco_base  NUMERIC(10, 2) NOT NULL CHECK (preco_base > 0),
    sazonal     BOOLEAN        NOT NULL DEFAULT FALSE,
    ativo       BOOLEAN        NOT NULL DEFAULT TRUE
);

-- Cardápio por unidade: preço local e janela de vigência (itens sazonais/juninos)
CREATE TABLE item_cardapio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id       BIGINT         NOT NULL REFERENCES unidade (id),
    produto_id       BIGINT         NOT NULL REFERENCES produto (id),
    preco            NUMERIC(10, 2) NOT NULL CHECK (preco > 0),
    disponivel       BOOLEAN        NOT NULL DEFAULT TRUE,
    inicio_vigencia  DATE,
    fim_vigencia     DATE,
    CONSTRAINT uk_cardapio_unidade_produto UNIQUE (unidade_id, produto_id),
    CONSTRAINT ck_cardapio_vigencia CHECK (fim_vigencia IS NULL OR inicio_vigencia IS NULL OR fim_vigencia >= inicio_vigencia)
);

-- Estoque por unidade
CREATE TABLE estoque (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id     BIGINT    NOT NULL REFERENCES unidade (id),
    produto_id     BIGINT    NOT NULL REFERENCES produto (id),
    quantidade     INTEGER   NOT NULL CHECK (quantidade >= 0),
    atualizado_em  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_estoque_unidade_produto UNIQUE (unidade_id, produto_id)
);

CREATE TABLE usuario (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome         VARCHAR(120) NOT NULL,
    email        VARCHAR(160) NOT NULL UNIQUE,
    senha_hash   VARCHAR(100) NOT NULL,
    perfil       VARCHAR(20)  NOT NULL CHECK (perfil IN ('CLIENTE', 'ATENDENTE', 'COZINHA', 'GERENTE', 'MATRIZ')),
    unidade_id   BIGINT REFERENCES unidade (id),
    cpf          VARCHAR(14),
    telefone     VARCHAR(20),
    anonimizado  BOOLEAN      NOT NULL DEFAULT FALSE,
    ativo        BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em    TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Histórico de consentimentos LGPD (somente inserção)
CREATE TABLE consentimento (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT      NOT NULL REFERENCES usuario (id),
    finalidade     VARCHAR(40) NOT NULL,
    concedido      BOOLEAN     NOT NULL,
    versao_termo   VARCHAR(20) NOT NULL,
    canal_origem   VARCHAR(20),
    registrado_em  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_consentimento_usuario ON consentimento (usuario_id, finalidade, registrado_em);

CREATE TABLE conta_fidelidade (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT  NOT NULL UNIQUE REFERENCES usuario (id),
    pontos      INTEGER NOT NULL DEFAULT 0 CHECK (pontos >= 0)
);

CREATE TABLE pedido (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unidade_id           BIGINT         NOT NULL REFERENCES unidade (id),
    cliente_id           BIGINT REFERENCES usuario (id),
    criado_por_id        BIGINT         NOT NULL REFERENCES usuario (id),
    canal                VARCHAR(20)    NOT NULL CHECK (canal IN ('APP', 'TOTEM', 'BALCAO', 'PICKUP', 'WEB')),
    status               VARCHAR(30)    NOT NULL,
    subtotal             NUMERIC(10, 2) NOT NULL,
    desconto             NUMERIC(10, 2) NOT NULL DEFAULT 0,
    total                NUMERIC(10, 2) NOT NULL,
    observacao           VARCHAR(300),
    idempotency_key      VARCHAR(80) UNIQUE,
    motivo_cancelamento  VARCHAR(300),
    criado_em            TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em        TIMESTAMP WITH TIME ZONE NOT NULL,
    versao               BIGINT
);
CREATE INDEX ix_pedido_unidade_status ON pedido (unidade_id, status, criado_em);
CREATE INDEX ix_pedido_cliente ON pedido (cliente_id);
CREATE INDEX ix_pedido_canal ON pedido (canal, criado_em);

CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id),
    produto_id      BIGINT         NOT NULL REFERENCES produto (id),
    quantidade      INTEGER        NOT NULL CHECK (quantidade > 0),
    preco_unitario  NUMERIC(10, 2) NOT NULL,
    subtotal        NUMERIC(10, 2) NOT NULL
);
CREATE INDEX ix_item_pedido_pedido ON item_pedido (pedido_id);

CREATE TABLE pagamento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id          BIGINT         NOT NULL REFERENCES pedido (id),
    valor              NUMERIC(10, 2) NOT NULL,
    metodo             VARCHAR(20)    NOT NULL,
    status             VARCHAR(20)    NOT NULL,
    transacao_externa  VARCHAR(80) UNIQUE,
    idempotency_key    VARCHAR(80) UNIQUE,
    tentativas         INTEGER        NOT NULL DEFAULT 0,
    ultima_mensagem    VARCHAR(300),
    criado_em          TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em      TIMESTAMP WITH TIME ZONE NOT NULL,
    versao             BIGINT
);
CREATE INDEX ix_pagamento_pedido ON pagamento (pedido_id);
CREATE INDEX ix_pagamento_status ON pagamento (status, atualizado_em);

-- Webhooks já processados (idempotência)
CREATE TABLE evento_pagamento_recebido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento_id        VARCHAR(80) NOT NULL UNIQUE,
    pagamento_id     BIGINT      NOT NULL REFERENCES pagamento (id),
    status_recebido  VARCHAR(20) NOT NULL,
    recebido_em      TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Trilha de auditoria (somente inserção)
CREATE TABLE registro_auditoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     BIGINT,
    usuario_email  VARCHAR(160),
    perfil         VARCHAR(20),
    unidade_id     BIGINT,
    acao           VARCHAR(50)  NOT NULL,
    entidade       VARCHAR(50)  NOT NULL,
    entidade_id    BIGINT,
    detalhes       VARCHAR(2000),
    ip             VARCHAR(60),
    data_hora      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_auditoria_unidade_data ON registro_auditoria (unidade_id, data_hora);
CREATE INDEX ix_auditoria_entidade ON registro_auditoria (entidade, entidade_id);
CREATE INDEX ix_auditoria_acao ON registro_auditoria (acao, data_hora);
